def get_locale_from_path(path):
    if path == "/kk" or path.startswith("/kk/"):
        return "kk"
    return "ru"


def get_base_path(path):
    if path == "/kk":
        return "/"
    if path.startswith("/kk/"):
        return path[3:]
    return path


def get_locale_path(path, locale):
    base = get_base_path(path)
    if locale == "kk":
        return "/kk" if base == "/" else "/kk" + base
    return base


